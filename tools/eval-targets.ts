// Bake every target, render templates, then simulate noisy perspective attempts
// (curl/spread/orientation noise, either hand) and report genuine vs impostor IoU.
import { HandPose, JOINT_COUNT, clonePose, curl, spread, orient, mirror, Finger } from '../src/shadow/hand-model';
import { setRadialGain, FlatHand, Mask, Matcher, NORM, drawHand, projectFromLight, ScreenFrame } from '../src/shadow/silhouette';
import { TARGETS, bakeTarget } from '../src/shadow/targets';
// @ts-ignore
import { writeSheet } from './sheet.mjs';

const out = process.argv[2];
setRadialGain(Number(process.argv[3] ?? 3));
const genMean: Record<string, number> = {};
const baked = TARGETS.map(bakeTarget);
const tiles: any[] = baked.map((b) => ({ w: NORM, h: NORM, data: b.template, label: b.def.id }));

let seed = 7; const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
const nz = (a: number) => (rnd() * 2 - 1) * a;
const screen: ScreenFrame = { ox: 0, oy: 0.26, oz: -0.75, rx: 1, ry: 0, rz: 0, ux: 0, uy: 1, uz: 0, nx: 0, ny: 0, nz: 1 };
const live = new Mask(150, 100, -0.45, -0.25, 0.006);
const joints = new Float32Array(JOINT_COUNT * 3);
const flat = new FlatHand();
const matcher = new Matcher();
const fingers: Finger[] = ['thumb', 'index', 'middle', 'ring', 'pinky'];

function attempt(pose: HandPose, noise: number, dist: number): Mask {
  let p = clonePose(pose);
  for (const f of fingers) { curl(p, f, nz(0.12 * noise)); spread(p, f, nz(5 * noise)); }
  orient(p, [nz(15 * noise), nz(15 * noise), nz(20 * noise)]);
  if (rnd() < 0.5) p = mirror(p);
  const w = [0, 0, 0];
  for (let j = 0; j < JOINT_COUNT; j++) for (let c = 0; c < 3; c++) w[c] += p.mats[j * 16 + 12 + c] / JOINT_COUNT;
  const ox = nz(0.05), oy = nz(0.05);
  for (let j = 0; j < JOINT_COUNT; j++) {
    joints[j * 3] = p.mats[j * 16 + 12] - w[0] + ox;
    joints[j * 3 + 1] = p.mats[j * 16 + 13] - w[1] + oy + 0.26 * dist / 0.75;
    joints[j * 3 + 2] = p.mats[j * 16 + 14] - w[2] - dist;
  }
  projectFromLight(joints, p.radii, 0, 0, 0, screen, flat);
  live.clear(); drawHand(live, flat);
  return live;
}

for (const noise of [0.5, 1.0]) {
  console.log(`\n== noise ${noise}: rows = attempted pose, cols = template; mean IoU (min genuine)`);
  console.log('         ' + baked.map((b) => b.def.id.padStart(8)).join(''));
  for (const a of baked) {
    const sums = baked.map(() => 0); let minG = 1; const N = 40;
    for (let k = 0; k < N; k++) {
      const m = attempt(a.pose, noise, 0.3 + nz(0.07));
      baked.forEach((b, i) => { const s = matcher.score(m, b.template); sums[i] += s / N; if (b === a) minG = Math.min(minG, s); });
      if (k === 0 && noise === 1) tiles.push({ w: live.w, h: live.h, data: live.data.slice(), label: 'attempt ' + a.def.id });
    }
    if (noise === 0.5) genMean[a.def.id] = sums[baked.indexOf(a)];
    console.log(a.def.id.padEnd(9) + sums.map((s) => s.toFixed(2).padStart(8)).join('') + `   minG=${minG.toFixed(2)}`);
  }
}
writeSheet(out, tiles, 6, out.replace('.png', '.txt'));

// Casual hands a player might hold without trying: they must not pass a target.
import { basePoses, shape } from '../src/shadow/hand-model';
const casual: Record<string, () => HandPose> = {
  relaxed: basePoses.relaxed, point: basePoses.point, pinch: basePoses.pinch,
  fist: () => shape(basePoses.relaxed(), { thumb: 0.7, index: 1, middle: 1, ring: 1, pinky: 1 }),
};
console.log('\n== casual hands, random orientation (±60°): p95 IoU per template');
const rows: number[][] = baked.map(() => []);
for (const make of Object.values(casual)) {
  for (let k = 0; k < 60; k++) {
    const p = make(); orient(p, [nz(60), nz(60), nz(60)]);
    const m = attempt(p, 0.5, 0.3 + nz(0.07));
    baked.forEach((b, i) => rows[i].push(matcher.score(m, b.template)));
  }
}
const pass: Record<string, number> = {};
baked.forEach((b, i) => { const v = rows[i].sort((a, c) => a - c);
  const p95 = v[Math.floor(v.length * 0.95)];
  pass[b.def.id] = +Math.min(0.8, Math.max(0.5, (genMean[b.def.id] + p95) / 2)).toFixed(3);
  console.log(b.def.id.padEnd(9), 'p95', v[Math.floor(v.length * 0.95)].toFixed(2), 'max', v[v.length - 1].toFixed(2), 'gen', genMean[b.def.id].toFixed(2), 'PASS', pass[b.def.id]); });
import { writeFileSync } from 'node:fs';
if (process.argv[4]) writeFileSync(process.argv[4], `// Generated by tools/eval-targets.ts: midpoint between the genuine mean
// (noisy attempts) and the p95 of casual hands, clamped to [0.5, 0.8].
export const PASS: Record<string, number> = ${JSON.stringify(pass, null, 2)};
`);
