// Extracts IWER's captured left-hand poses (MIT, Meta Platforms) into a typed module.
import { writeFileSync } from 'node:fs';
const out = ['// Generated by tools/extract-base-poses.mjs from iwer hand configs (MIT, Meta Platforms).',
  '// Left-hand joint transforms in hand space, column-major 4x4, WebXR joint order.', ''];
const names = ['relaxed', 'point', 'pinch'];
let order;
for (const name of names) {
  const m = await import(`../node_modules/iwer/lib/device/configs/hand/${name}.js`);
  const pose = Object.values(m)[0];
  order ??= Object.keys(pose.jointTransforms);
  const mats = order.map((j) => Array.from(pose.jointTransforms[j].offsetMatrix, (x) => +x.toFixed(5)));
  const radii = order.map((j) => +pose.jointTransforms[j].radius.toFixed(5));
  out.push(`export const ${name.toUpperCase()}_MATS: readonly number[] = [${mats.flat().join(',')}];`);
  out.push(`export const ${name.toUpperCase()}_RADII: readonly number[] = [${radii.join(',')}];`, '');
}
out.push(`export const JOINT_NAMES = ${JSON.stringify(order)} as const;`);
writeFileSync(new URL('../src/shadow/base-poses.ts', import.meta.url), out.join('\n') + '\n');
console.log('joints', order.length);
